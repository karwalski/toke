#!/usr/bin/env python3
"""gen_tki_quarantine_h.py — the quarantined stdlib exports the type checker
rejects at `--check` (story 127.224 item 4, 127.218's remainder).

Output: src/stdlib_quarantine_gen.h (included by src/types.c).

An entry is the glue SYMBOL the compiler emits for an export listed in
scripts/check_tki_skiplist.txt (the single authoritative record of the
quarantine, 136.7), computed with check_tki_coverage.py's own resolver so the
two can never disagree about the name.

The skiplist alone is not taken as proof that the symbol is missing:
check_tki_coverage.py recognises a definition only in the `<type> tk_x(...) {`
shape, so glue instantiated through a macro (`TK_IMG_XFORM(tk_image_fliph_w,
image_flip_h)`) reads as absent, and a program calling it links and runs.  A
symbol that occurs as a word ANYWHERE in src/stdlib/*.c is therefore dropped
here — rejecting a program that links is the 136.36 mistake.  What remains is
declared by an interface, quarantined, and named by no C source at all.

Usage:
    python3 scripts/gen_tki_quarantine_h.py [--check]
    --check: exit 1 if the checked-in header differs from what would be written.
"""

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
import check_tki_coverage as ctc  # noqa: E402

OUTPUT = REPO / "src" / "stdlib_quarantine_gen.h"


def quarantined_symbols() -> tuple[list[tuple[str, str, str]], list[str]]:
    skips = ctc.load_skiplist(ctc.SKIPLIST)
    explicit, patterns, subns = ctc.load_resolver_tables(REPO / "src" / "llvm.c")
    csrc = "\n".join(p.read_text(errors="replace")
                     for p in sorted((REPO / "src" / "stdlib").glob("*.c")))
    keep, dropped = [], []
    for key in sorted(skips):
        tki_name, _, name = key.partition("::")
        path = ctc.TKI_DIR / tki_name
        try:
            module = json.loads(path.read_text()).get("module", "")
        except (OSError, json.JSONDecodeError):
            continue
        mod = module[4:] if module.startswith("std.") else module
        prefix, _, method = name.partition(".")
        if not method:
            prefix, method = mod, name
        if "." in method:           # `http.res.ok` — not an alias.member call
            continue
        sym = ctc.expected_symbol(mod, prefix, method, explicit, patterns, subns)
        if re.search(r"\b" + re.escape(sym) + r"\b", csrc):
            dropped.append(f"{key} -> {sym}")
            continue
        keep.append((sym, module, method))
    return keep, dropped


def render(keep, dropped) -> str:
    out = [
        "/* stdlib_quarantine_gen.h — AUTO-GENERATED by scripts/gen_tki_quarantine_h.py",
        " * Do not edit manually. Regenerate with: python3 scripts/gen_tki_quarantine_h.py",
        " *",
        " * Story 127.224. Glue symbols of quarantined interface exports",
        " * (scripts/check_tki_skiplist.txt) that no stdlib C source names at all.",
        f" * {len(keep)} symbols; {len(dropped)} skiplist entries dropped because a C source names",
        " * their symbol (a macro-instantiated definition the coverage scan misses):",
    ]
    out += [f" *   {d}" for d in dropped]
    out += [" */", ""]
    out += [f'    {{ "{s}", "{m}", "{e}" }},' for s, m, e in keep]
    return "\n".join(out) + "\n"


def main() -> int:
    text = render(*quarantined_symbols())
    if "--check" in sys.argv[1:]:
        cur = OUTPUT.read_text() if OUTPUT.exists() else ""
        if cur != text:
            print(f"STALE: {OUTPUT.relative_to(REPO)} differs from the skiplist; "
                  "run python3 scripts/gen_tki_quarantine_h.py")
            return 1
        print(f"OK: {OUTPUT.relative_to(REPO)} matches the skiplist")
        return 0
    OUTPUT.write_text(text)
    print(f"Written to {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
