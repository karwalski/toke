#!/usr/bin/env python3
"""check_stdlib_signatures.py -- docs/spec/stdlib-signatures.md agrees with the
.tki interfaces, which are normative (story 127.456).

THE DEFECT.  stdlib-signatures.md calls itself "the normative interface for the
toke standard library", but it is written by hand and nothing ever read it back
against stdlib/*.tki -- the files the compiler actually resolves std calls
from.  By 2026-11-15 it had drifted: most modules had no block at all, the
std.log block disagreed with log.tki, and std.csv had no block.

THE RULE.  stdlib/<m>.tki is the normative signature of std.<m>: it is what
`tkc` type-checks every call against, what the conformance tests exercise and
what docs/stdlib/<m>.md is already held to (check_stdlib_doc_exports.py).
This page is held to the .tki the same way:

  1. Every `f=` line in a `### std.<m>` block names a func export of
     stdlib/<m>.tki (a module qualifier `json.x` is read as `x`).
  2. Its parameter count equals the export's, and -- unless the export is
     tagged "gen":"abi", whose types are placeholders -- each parameter type
     and the return type equal the export's after the spelling normalisation
     check_stdlib_doc_exports.py uses (imported, not copied).
  3. Every `t=$name` line names a type export of that .tki.
  4. COVERAGE.  The section between the GENERATED markers is rendered from
     the .tki (`--write`): for every public module with no hand-written block,
     its public types and non-abi func exports.  It is never edited by hand;
     `--check` (run by `make check-tki`) fails when it is stale.  Parameter
     names there are positional (`a`, `b`, ...) because a .tki carries types,
     not names.

An `f=` line can be excused from rules 1-2 only by a `(* not exported ... *)`
comment on the same line, which says in the page that no interface declares it.

Usage:  python3 scripts/check_stdlib_signatures.py [--check | --write | --report]
        --check   (default) fail on any disagreement or a stale generated section
        --write   re-render the generated section from the .tki
        --report  list every disagreement, never fail
"""
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from check_stdlib_doc_exports import norm, split_top, split_params  # noqa: E402

DOC = REPO / "docs" / "spec" / "stdlib-signatures.md"
TKI = REPO / "stdlib"
BEGIN = ("<!-- BEGIN GENERATED by scripts/check_stdlib_signatures.py --write "
         "from stdlib/*.tki (story 127.456). Do not edit by hand. -->")
END = "<!-- END GENERATED -->"
NOT_EXPORTED = re.compile(r"\(\*\s*not exported", re.I)
SECTION = re.compile(r"^###\s+std\.([a-z][a-z0-9]*)\s*$")


def load_tki():
    """{module stem: (funcs {name: export}, types {name: export}, internal set)}."""
    mods = {}
    for f in sorted(TKI.glob("*.tki")):
        try:
            data = json.loads(f.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        mod = (data.get("module") or "").removeprefix("std.")
        if not mod:
            continue
        funcs, types = {}, {}
        for e in data.get("exports") or []:
            name = (e.get("name") or "").split(".")[-1]
            if e.get("kind") == "func" and name:
                funcs[name] = e
            elif e.get("kind") == "type" and name:
                types[name.lstrip("$").lower()] = e
        mods[mod] = (funcs, types)
    return mods


def strip_comments(text):
    """Drop (* ... *) comments, which may span lines."""
    return re.sub(r"\(\*.*?\*\)", "", text, flags=re.S)


def doc_entries(lines):
    """[(module, lineno, kind, raw line)] for the hand-written blocks only."""
    out, mod, fence, in_gen = [], None, False, False
    for i, line in enumerate(lines, 1):
        if line.strip() == BEGIN:
            in_gen = True
        elif line.strip() == END:
            in_gen = False
            continue
        if in_gen:
            continue
        m = SECTION.match(line)
        if m:
            mod = m.group(1)
            continue
        if line.startswith("## "):
            mod = None
        if line.strip().startswith("```"):
            fence = not fence
            continue
        if fence and mod and re.match(r"\s*[ft]=", line):
            out.append((mod, i, line.strip()[0], line.rstrip()))
    return out


def parse_func(line):
    """(name, [param types], return) of `f=name(a:T;b:U):R`, or None."""
    body = strip_comments(line).strip()[2:].strip()
    m = re.match(r"([A-Za-z0-9_.]+)\(", body)
    if not m:
        return None
    rest = body[m.end() - 1:]
    depth = 0
    for k, c in enumerate(rest):
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                params = split_params(rest[1:k])
                tail = rest[k + 1:].strip()
                ret = tail[1:].strip() if tail.startswith(":") else ""
                return m.group(1).split(".")[-1], params, ret
    return None


def problems(lines, mods):
    out = []
    documented = set()
    for mod, ln, kind, raw in doc_entries(lines):
        documented.add(mod)
        where = "%s:%d" % (DOC.relative_to(REPO), ln)
        if mod not in mods:
            out.append((where, "std.%s has no stdlib/*.tki interface" % mod, raw))
            continue
        funcs, types = mods[mod]
        if kind == "t":
            m = re.match(r"\s*t=\$?([A-Za-z0-9_]+)", raw)
            if m and m.group(1).lower() not in types and not NOT_EXPORTED.search(raw):
                out.append((where, "type $%s is not declared by %s.tki"
                            % (m.group(1), mod), raw))
            continue
        sig = parse_func(raw)
        if not sig:
            out.append((where, "unparseable f= line", raw))
            continue
        name, params, ret = sig
        if NOT_EXPORTED.search(raw):
            if name in funcs:
                out.append((where, "%s.%s is marked not exported but %s.tki exports it"
                            % (mod, name, mod), raw))
            continue
        exp = funcs.get(name)
        if exp is None:
            out.append((where, "%s.%s is not an export of %s.tki" % (mod, name, mod), raw))
            continue
        want = exp.get("params") or []
        if len(params) != len(want):
            out.append((where, "%s.%s: %d parameter(s) here, %s.tki declares %d (%s)"
                        % (mod, name, len(params), mod, len(want), "; ".join(want)), raw))
            continue
        if exp.get("gen") == "abi":
            continue
        for k, (g, w) in enumerate(zip(params, want)):
            if norm(g) != norm(w):
                out.append((where, "%s.%s: parameter %d is `%s` here, `%s` in %s.tki"
                            % (mod, name, k + 1, g, w, mod), raw))
                break
        else:
            if norm(ret) != norm(exp.get("return") or ""):
                out.append((where, "%s.%s: returns `%s` here, `%s` in %s.tki"
                            % (mod, name, ret, exp.get("return"), mod), raw))
    return out, documented


def surface(t):
    """A .tki type in the page's surface spelling: str -> $str, [T] -> @(T).

    Interfaces spell types two ways: the bracket form (`str`, `[[str]]`,
    `str!fileerr`) and, in some hand-written .tki, the surface form already
    (`$str`, `@(byte)`, `fn($x):void`).  The latter is left as written."""
    t = t.strip()
    if "$" in t or "@" in t or t.startswith("fn("):
        return t
    if t.startswith("[") and t.endswith("]"):
        inner = split_top(t[1:-1], ":")
        return "@(" + ":".join(surface(x) for x in inner) + ")"
    if "!" in t:
        a, b = t.split("!", 1)
        return surface(a) + "!" + surface(b)
    if t.startswith("?(") and t.endswith(")"):
        return "?(" + surface(t[2:-1]) + ")"
    if re.fullmatch(r"[iu](8|16|32|64)|f(32|64)|bool|void|byte", t):
        return t
    return "$" + t


def render(mods, documented):
    out = [BEGIN, ""]
    names = "abcdefghijklmnopqrstuvwxyz"
    for mod in sorted(mods):
        if mod in documented:
            continue
        funcs, types = mods[mod]
        pub_f = [(n, e) for n, e in funcs.items()
                 if not e.get("internal") and e.get("gen") != "abi"]
        pub_t = [e for e in types.values() if not e.get("internal")]
        abi = sum(1 for e in funcs.values() if not e.get("internal") and e.get("gen") == "abi")
        if not pub_f and not pub_t and not abi:
            continue
        out.append("### std.%s (generated)" % mod)
        out.append("")
        out.append("```text")
        for e in sorted(pub_t, key=lambda e: e["name"]):
            out.append("t=$%s" % e["name"].split(".")[-1].lstrip("$"))
        for n, e in sorted(pub_f):
            ps = ";".join("%s:%s" % (names[k % 26], surface(p))
                          for k, p in enumerate(e.get("params") or []))
            out.append("f=%s(%s):%s" % (n, ps, surface(e.get("return") or "void")))
        out.append("```")
        if abi:
            out.append("")
            out.append("Plus %d `\"gen\":\"abi\"` export%s of `stdlib/%s.tki`, whose "
                       "types are ABI placeholders (only the arity is declared)."
                       % (abi, "" if abi == 1 else "s", mod))
        out.append("")
    out.append(END)
    return out


def splice(lines, gen):
    if BEGIN in [l.strip() for l in lines]:
        b = [l.strip() for l in lines].index(BEGIN)
        e = [l.strip() for l in lines].index(END, b)
        return lines[:b] + gen + lines[e + 1:]
    return None


def main():
    mode = (sys.argv[1] if len(sys.argv) > 1 else "--check")
    lines = DOC.read_text().split("\n")
    mods = load_tki()
    found, documented = problems(lines, mods)
    gen = render(mods, documented)
    new = splice(lines, gen)
    if mode == "--write":
        if new is None:
            sys.exit("check_stdlib_signatures: %s has no GENERATED markers" % DOC)
        DOC.write_text("\n".join(new))
        print("wrote the generated section of %s (%d modules with no hand-written block)"
              % (DOC.relative_to(REPO), sum(1 for l in gen if l.startswith("### "))))
        return 0
    for where, msg, raw in found:
        print("%s: %s\n    %s" % (where, msg, raw.strip()[:160]))
    stale = new is None or new != lines
    if stale:
        print("%s: the generated section is missing or stale -- run "
              "`python3 scripts/check_stdlib_signatures.py --write`" % DOC.relative_to(REPO))
    if mode == "--report":
        print("%d disagreement(s)" % len(found))
        return 0
    if found or stale:
        print("\ncheck_stdlib_signatures: FAILED -- stdlib/*.tki is normative; fix the page "
              "(or, if the page is right, the .tki with its spec amendment and tests).")
        return 1
    print("check_stdlib_signatures: OK -- %d hand-written entries agree with stdlib/*.tki; "
          "generated section current" % len(doc_entries(lines)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
