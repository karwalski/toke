#!/usr/bin/env python3
"""136.58 — render docs/reference/combinator-status.md from the probe JSON.

The document's verdict cells used to be transcribed by hand from
patterns/probe/probe_results.json.  The JSON stayed right and the Markdown
rotted: ~20 rows claimed breakage that had been fixed, some for three months.
This script is the only writer of those cells now.

Inputs
  patterns/probe/combinator-status.md.tmpl   hand-written prose + notes, with
                                             placeholders where measurements go
  patterns/probe/probe_results.json          the measurement (run_probes.sh)

Placeholders
  {{row:p1,p2,...}}          the four verdict cells  --check | build | runs | correct
                             for probes p1..pn.  Every listed probe must render
                             the SAME four cells, or rendering fails: a row may
                             not paper over a disagreement between its probes.
  {{row:p1,...;mark=*}}      as above, with a marker appended to `correct`
  {{pin.version}} {{pin.bin_sha}} {{pin.tree}} {{pin.generated}}
  {{summary.probes}} {{summary.correct}} {{summary.check_ok}} ...
  {{generated_notice}}       the do-not-edit banner

Rendering also fails when
  - a probe named in the template is not in the JSON;
  - a probe in the JSON is named by no row (it would silently drop out);
  - the JSON's probe set differs from the patterns/probe/*.tk files (a probe
    was added or removed and the JSON was not re-measured);
  - the JSON's summary does not match its own results.

Modes
  (default)            --check: exit 1 if the committed document differs from
                       the rendering, with a unified diff
  --write              write the document
  --compare FRESH      exit 1 if FRESH (a new run_probes.sh output) renders any
                       probe's four cells differently from the committed JSON.
                       This is check-probes' verdict: the committed measurement
                       no longer describes this compiler.
  --root DIR           operate on another tree (negative controls)
"""
import argparse
import difflib
import json
import pathlib
import re
import sys

PLACEHOLDER = re.compile(r"\{\{([a-z_]+)(?::([^}]*)|\.([a-z_]+))?\}\}")
NOTICE = ("<!-- GENERATED by scripts/render_combinator_status.py from "
          "patterns/probe/probe_results.json and "
          "patterns/probe/combinator-status.md.tmpl. Do not edit: edit the "
          "template (notes, prose) or re-run the probes (verdicts). "
          "`make check-combinator-status` fails on any hand edit. -->")


class RenderError(Exception):
    pass


def cells(r):
    """The four verdict cells for one probe result."""
    c, b, run = r["check"], r["build"], r["run"]
    if c["ok"]:
        check = "ok"
    else:
        check = "**%s**" % (",".join(c["codes"]) or "exit %d" % c["exit"])
    if not c["ok"]:
        build = "–"
    elif b["ok"]:
        build = "ok"
    else:
        build = ",".join(b["codes"]) or "exit %d" % b["exit"]
    if not (c["ok"] and b["ok"]) or run is None:
        runs = "–"
    elif run["exit"] == 0:
        runs = "ok"
    elif run["exit"] == 139:
        runs = "**SIGSEGV**"
    elif run["exit"] == 134:
        runs = "**SIGABRT**"
    else:
        runs = "**exit %d**" % run["exit"]
    if r["correct"]:
        correct = "yes"
    elif runs == "ok":
        correct = "**WRONG**"
    else:
        correct = "no"
    return (check, build, runs, correct)


def load(root):
    j = json.loads((root / "patterns/probe/probe_results.json").read_text())
    by = {r["probe"]: r for r in j["results"]}
    if len(by) != len(j["results"]):
        raise RenderError("probe_results.json lists a probe twice")
    return j, by


def validate(root, j, by):
    tk = {p.stem for p in (root / "patterns/probe").glob("*.tk")}
    if tk != set(by):
        missing = sorted(tk - set(by))
        extra = sorted(set(by) - tk)
        raise RenderError(
            "probe_results.json is not a measurement of patterns/probe/: "
            "%s%s -- re-run `make render-combinator-status PROBES=1`"
            % ("no result for %s" % ", ".join(missing) if missing else "",
               ("; " if missing and extra else "")
               + ("result for a deleted probe %s" % ", ".join(extra) if extra else "")))
    rs = j["results"]
    want = {"probes": len(rs),
            "check_ok": sum(r["check"]["ok"] for r in rs),
            "build_ok": sum(r["build"]["ok"] for r in rs),
            "run_ok": sum(1 for r in rs if r["run"] and r["run"]["ok"]),
            "correct": sum(r["correct"] for r in rs)}
    if j.get("summary") != want:
        raise RenderError("probe_results.json summary %s does not match its "
                          "results %s" % (j.get("summary"), want))


def render(root):
    j, by = load(root)
    validate(root, j, by)
    tmpl = (root / "patterns/probe/combinator-status.md.tmpl").read_text()
    used = set()
    pin = {"version": j["tkc_version"], "bin_sha": j["tkc_bin_sha"],
           "tree": j["tkc_sha"], "generated": j["generated"]}

    def sub(m):
        kind, arg, field = m.group(1), m.group(2), m.group(3)
        if kind == "generated_notice":
            return NOTICE
        if kind == "pin" and field in pin:
            return str(pin[field])
        if kind == "summary" and field in j["summary"]:
            return str(j["summary"][field])
        if kind == "row" and arg:
            spec, _, opt = arg.partition(";")
            mark = opt[len("mark="):] if opt.startswith("mark=") else ""
            if opt and not mark:
                raise RenderError("bad row option %r" % opt)
            names = [n.strip() for n in spec.split(",") if n.strip()]
            got = []
            for n in names:
                if n not in by:
                    raise RenderError("template names probe %r, which is not "
                                      "in probe_results.json" % n)
                used.add(n)
                got.append((n, cells(by[n])))
            distinct = {c for _, c in got}
            if len(distinct) != 1:
                raise RenderError(
                    "row {{row:%s}}: its probes disagree -- %s. Split the row."
                    % (arg, "; ".join("%s=%s" % (n, "|".join(c)) for n, c in got)))
            c = list(distinct.pop())
            c[3] += mark
            return " | ".join(c)
        raise RenderError("unknown placeholder %s" % m.group(0))

    out = PLACEHOLDER.sub(sub, tmpl)
    unused = sorted(set(by) - used)
    if unused:
        raise RenderError("no row names probe(s) %s -- every probe must back a "
                          "row, or it silently drops out" % ", ".join(unused))
    return out


def compare(root, fresh_path):
    _, old = load(root)
    fresh = {r["probe"]: r for r in json.loads(pathlib.Path(fresh_path).read_text())["results"]}
    bad = []
    for n in sorted(set(old) | set(fresh)):
        if n not in fresh:
            bad.append("  %-28s committed, but the fresh run has no result" % n)
        elif n not in old:
            bad.append("  %-28s measured now, absent from the committed JSON" % n)
        else:
            a, b = cells(old[n]), cells(fresh[n])
            if a != b or old[n]["correct"] != fresh[n]["correct"]:
                bad.append("  %-28s committed %s  ->  now %s"
                           % (n, " | ".join(a), " | ".join(b)))
    if bad:
        print("check-probes: FAIL -- %d probe(s) no longer measure what "
              "patterns/probe/probe_results.json records:" % len(bad))
        print("\n".join(bad))
        print("Re-measure and re-render in the commit that changed the "
              "compiler: make render-combinator-status PROBES=1")
        return 1
    print("check-probes: OK -- all %d probes measure what the committed JSON "
          "records" % len(old))
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=pathlib.Path,
                    default=pathlib.Path(__file__).resolve().parent.parent)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--compare", metavar="FRESH_JSON")
    a = ap.parse_args()
    root = a.root.resolve()
    try:
        if a.compare:
            return compare(root, a.compare)
        text = render(root)
    except RenderError as e:
        print("render-combinator-status: FAIL -- %s" % e)
        return 1
    doc = root / "docs/reference/combinator-status.md"
    if a.write:
        doc.write_text(text)
        print("wrote %s" % doc.relative_to(root))
        return 0
    have = doc.read_text() if doc.exists() else ""
    if have != text:
        print("check-combinator-status: FAIL -- %s differs from its rendering "
              "(hand edit, or the JSON/template changed without a re-render):"
              % doc.relative_to(root))
        sys.stdout.writelines(list(difflib.unified_diff(
            have.splitlines(True), text.splitlines(True),
            "committed", "rendered", n=0))[:60])
        print("Fix: make render-combinator-status")
        return 1
    print("check-combinator-status: OK -- document matches its rendering "
          "(%d probes)" % len(load(root)[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
