#!/usr/bin/env python3
"""gbnf_gate.py — drift gate: docs/spec/toke.gbnf against the real parser (story 131.52).

The claim the gate enforces, over a committed fragment set:

    toke.gbnf accepts F   <=>   tkc parses F

"tkc parses F" is `tkc --dump-ast F` exiting 0 (lexer + parser only, no name
resolution or type checking: the grammar is a syntax artefact, and `--check`
would reject well-formed programs for type errors) with no RECOVERY
diagnostic.  A recovery diagnostic is a warning the front end emits while it
silently repairs input that is not toke -- `# ...` / `// ...` line comments
(W1020, comment form), `if(c):{` and `let mut x` (W2021), `mut x` without the
dot (W2022).  A constrained decoder must never produce those, so for this
gate they count as rejections.  Hints that do not repair anything (W1011,
W2020, W1021, the foreign-keyword form of W1020) do not.

Fragment set: test/gbnf/fragments.json, regenerated by `--write-fragments`
from the conformance YAML inputs (L/G/N/T/D series), test/standalone,
examples/, the tree-sitter corpus at ~/tk/toke-spec/tree-sitter-toke/test/corpus
(when present) and test/gbnf/extra/*.tk, plus deterministic single-edit
mutants of every seed (a delete, an insert, a whitespace removal).  The
mutants are what makes the gate bite: nearly every real program parses, so
seeds alone only test the accept side.

Known divergences are listed in KNOWN below, each with the reason the
grammar cannot (context-free) or does not follow the parser.  A divergence
not in KNOWN fails the gate; a KNOWN entry that no longer diverges fails it
too, so the list cannot go stale.

Usage:
  gbnf_gate.py                       run the gate (exit 1 on any unexplained divergence)
  gbnf_gate.py --write-fragments     regenerate test/gbnf/fragments.json
  gbnf_gate.py --show ID             print one fragment and both verdicts
  gbnf_gate.py --corpus DIR --sample N   also check N stride-sampled corpus
                                     records (local only; never committed)
"""
from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
import random
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
from gbnf_earley import Grammar  # noqa: E402

GBNF = ROOT / "docs" / "spec" / "toke.gbnf"
FRAGMENTS = ROOT / "test" / "gbnf" / "fragments.json"
EXTRA = ROOT / "test" / "gbnf" / "extra"
TS_CORPUS = Path(os.environ.get("TOKE_TS_CORPUS",
                                Path.home() / "tk" / "toke-spec" / "tree-sitter-toke" / "test" / "corpus"))
MAX_LEN = 4000          # characters; longer seeds are skipped (Earley is cubic in the worst case)
MUTANT_ROUNDS = 1     # committed set: one delete, one insert, one whitespace drop per seed

# id -> reason.  Every entry is a context-sensitive rule of the parser that a
# context-free grammar does not express (or expresses only at a cost the
# decoder would pay on every token).  Keep this short; it is a list of the
# grammar's honest over-approximations, not a place to park drift.
_DUP = ("E2015 duplicate field name: the parser compares field names as it goes; "
        "a CFG cannot remember a set of names")
_E1006 = ("E1006: the lexer rejects a single upper-case M/F/T/I/C directly followed by `=` "
          "(`C==1`), a one-character lookahead on an otherwise ordinary type name")
_SPAWN = ("`spawn` is an expression keyword only inside `sc{...}` (parser in_sc state); the "
          "grammar allows it everywhere instead of duplicating every statement and expression rule")
_NOTSL = ("`!` on a PARENTHESISED struct literal: the parser unwraps any depth of parentheses "
          "before its E2002 check; the grammar rejects only the bare `!$t{..}` form")
_FN = ("`fn` used as a plain name with a postfix (`fn.x`): `fn(` opens a closure, and the grammar "
       "gives the bare name no postfix rather than split every tail rule on its first element "
       "(under-approximation; the lexer warns W1020 on `fn` as a name)")
KNOWN: dict[str, str] = {
    "78888dc2f4d4": _DUP, "655ed8fa089e": _DUP, "f134f743d983": _DUP,
    "f1de6173a24a": _E1006, "84b9b547153c": _E1006, "aeefef26f76a": _E1006,
    "f1a53297b683": _SPAWN, "83c54895094f": _SPAWN, "97dbd731b905": _SPAWN,
    "001e3711c97b": _NOTSL, "8e1523f78654": _NOTSL, "9adf20ab762d": _NOTSL,
    "801672a6590f": _FN, "c1512f75758a": _FN,
}

RECOVERY = {"W2021", "W2022"}


def tkc_path() -> str:
    return os.environ.get("TKC", str(ROOT / "tkc"))


# ---------------------------------------------------------------- oracle ----
def oracle(text: str, tkc: str | None = None) -> tuple[bool, str]:
    """(accepted, reason) from the real front end."""
    fd, p = tempfile.mkstemp(suffix=".tk", prefix="gbnf131_")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        env = dict(os.environ, TKC_STDLIB_DIR=str(ROOT / "src" / "stdlib"))
        r = subprocess.run([tkc or tkc_path(), "--dump-ast", p], capture_output=True,
                           text=True, errors="replace", timeout=30, env=env)
    finally:
        os.unlink(p)
    codes = []
    for line in (r.stderr or "").splitlines():
        try:
            d = json.loads(line)
        except ValueError:
            continue
        code = d.get("error_code", "")
        if code in RECOVERY or (code == "W1020" and "comment" in d.get("message", "")):
            return False, f"recovery {code}"
        codes.append(code)
    if r.returncode != 0:
        return False, ",".join(c for c in codes if c.startswith("E")) or f"rc={r.returncode}"
    return True, "ok"


# ------------------------------------------------------------- fragments ----
def _yaml_inputs(path: Path) -> list[str]:
    """`input: |` blocks of a conformance YAML file, without a YAML dependency."""
    out, lines, i = [], path.read_text(encoding="utf-8", errors="replace").splitlines(), 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("input:") and ln.rstrip().endswith(("|", "|-", "|+")):
            body, i = [], i + 1
            while i < len(lines) and (lines[i].startswith("  ") or not lines[i].strip()):
                body.append(lines[i][2:] if lines[i].startswith("  ") else "")
                i += 1
            while body and not body[-1].strip():
                body.pop()
            out.append("\n".join(body) + "\n")
            continue
        i += 1
    return out


def _ts_inputs(path: Path) -> list[str]:
    """Source blocks of a tree-sitter corpus file (between the === header and ---)."""
    out, lines, i = [], path.read_text(encoding="utf-8").splitlines(), 0
    while i < len(lines):
        if lines[i].startswith("====") and i + 2 < len(lines) and lines[i + 2].startswith("===="):
            j, body = i + 3, []
            while j < len(lines) and not lines[j].startswith("----"):
                body.append(lines[j])
                j += 1
            out.append("\n".join(body).strip("\n") + "\n")
            i = j
        else:
            i += 1
    return out


def seeds() -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for series in ("lexical", "grammar", "names", "types", "diagnostics"):
        for f in sorted((ROOT / "test" / series).glob("*.yaml")):
            for k, t in enumerate(_yaml_inputs(f)):
                found.append((f"{series}/{f.stem}#{k}", t))
    for f in sorted((ROOT / "test" / "standalone").glob("*.tk")):
        found.append((f"standalone/{f.name}", f.read_text(encoding="utf-8", errors="replace")))
    for f in sorted(glob.glob(str(ROOT / "examples" / "**" / "*.tk"), recursive=True)):
        found.append((os.path.relpath(f, ROOT), Path(f).read_text(encoding="utf-8", errors="replace")))
    if TS_CORPUS.is_dir():
        for f in sorted(TS_CORPUS.glob("*.txt")):
            for k, t in enumerate(_ts_inputs(f)):
                found.append((f"tree-sitter/{f.stem}#{k}", t))
    for f in sorted(EXTRA.glob("*.tk")):
        found.append((f"extra/{f.name}", f.read_text(encoding="utf-8")))
    return [(s, t) for s, t in found if 0 < len(t) <= MAX_LEN]


_INSERT = list("(){};:.=<>!&|@$\"*-+ \nx1") + ["el", "let ", "if", "mt ", "(*", "*)"]


def mutants(text: str, rounds: int = 1) -> list[tuple[str, str]]:
    """Deterministic single edits: delete one char, insert one token, drop one
    whitespace run (`rounds` of each).  The RNG is seeded by the text, so the
    set is stable."""
    rng = random.Random(int(hashlib.sha256(text.encode()).hexdigest()[:16], 16))
    out = []
    spaces = [k for k, c in enumerate(text) if c in " \n" and k > 0 and text[k - 1] not in " \n"]
    for r in range(rounds):
        sfx = "" if r == 0 else str(r)
        if len(text) > 1:
            k = rng.randrange(len(text))
            out.append(("del" + sfx, text[:k] + text[k + 1:]))
            k = rng.randrange(len(text) + 1)
            out.append(("ins" + sfx, text[:k] + rng.choice(_INSERT) + text[k:]))
        if spaces:
            k = rng.choice(spaces)
            e = k
            while e < len(text) and text[e] in " \n\t":
                e += 1
            out.append(("ws" + sfx, text[:k] + text[e:]))
    return out


def fid(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()[:12]


def build_fragments(rounds: int = 1, extra_seeds: list[tuple[str, str]] | None = None) -> list[dict]:
    frags, seen = [], set()
    for src, t in seeds() + (extra_seeds or []):
        for kind, text in [("seed", t)] + mutants(t, rounds):
            i = fid(text)
            if i in seen:
                continue
            seen.add(i)
            frags.append({"id": i, "src": src if kind == "seed" else f"{src}~{kind}", "text": text})
    return frags


def write_fragments() -> int:
    frags = build_fragments(MUTANT_ROUNDS)
    FRAGMENTS.parent.mkdir(parents=True, exist_ok=True)
    with open(FRAGMENTS, "w", encoding="utf-8") as fh:
        json.dump({"story": "131.52", "generator": "scripts/gbnf_gate.py --write-fragments",
                   "count": len(frags), "fragments": frags}, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    print(f"wrote {FRAGMENTS.relative_to(ROOT)}: {len(frags)} fragments")
    return 0


def load_fragments() -> list[dict]:
    return json.load(open(FRAGMENTS, encoding="utf-8"))["fragments"]


def corpus_sample(corpus: Path, n: int) -> list[dict]:
    files = sorted(glob.glob(str(corpus / "*-*" / "*.json")))
    step = max(1, len(files) // max(n, 1))
    out = []
    for f in files[::step][:n]:
        d = json.load(open(f, encoding="utf-8"))
        t = d.get("tk_source") or ""
        if t and len(t) <= MAX_LEN:
            out.append({"id": fid(t), "src": f"corpus/{Path(f).name}", "text": t})
    return out


# ------------------------------------------------------------------ gate ----
def static_checks(g: Grammar) -> list[str]:
    errs = []
    lr = g.left_recursive_rules()
    if lr:
        errs.append(f"left-recursive rules (llama.cpp GBNF loops on them): {', '.join(lr)}")
    un = g.unreachable_rules()
    if un:
        errs.append(f"unreachable rules: {', '.join(un)}")
    return errs


def run_gate(frags: list[dict], g: Grammar, verbose: bool = False, jobs: int = 4) -> dict:
    res = {"n": 0, "both_accept": 0, "both_reject": 0, "gbnf_only": [], "parser_only": [],
           "known_hit": [], "known_stale": []}
    hit = set()
    # the oracle is a subprocess per fragment: threads overlap them (the GIL is
    # released while tkc runs); the recogniser stays on this thread
    with ThreadPoolExecutor(max_workers=max(1, jobs)) as ex:
        verdicts = list(ex.map(lambda f: oracle(f["text"]), frags))
    for f, (pa, why) in zip(frags, verdicts):
        ga = g.accepts(f["text"])
        res["n"] += 1
        if ga == pa:
            res["both_accept" if ga else "both_reject"] += 1
            continue
        if f["id"] in KNOWN:
            hit.add(f["id"])
            res["known_hit"].append(f["id"])
            continue
        (res["gbnf_only"] if ga else res["parser_only"]).append({"id": f["id"], "src": f["src"], "parser": why})
        if verbose:
            print(f"DIVERGE {f['id']} {f['src']}: gbnf={'accept' if ga else 'reject'} parser={why}")
    ids = {f["id"] for f in frags}
    res["known_stale"] = sorted(k for k in KNOWN if k in ids and k not in hit)
    return res


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write-fragments", action="store_true")
    ap.add_argument("--show", metavar="ID")
    ap.add_argument("--corpus", type=Path)
    ap.add_argument("--sample", type=int, default=200)
    ap.add_argument("--stress", type=int, default=0, metavar="R",
                    help="local only: regenerate the set in memory with R mutant rounds per seed")
    ap.add_argument("--gbnf", type=Path, default=GBNF)
    ap.add_argument("--only", metavar="PREFIX", help="only fragments whose source starts with PREFIX "
                    "(e.g. extra/); for quick negative controls -- the gate proper runs them all")
    ap.add_argument("--jobs", type=int, default=int(os.environ.get("GBNF_GATE_JOBS", "3")),
                    help="parallel tkc oracle calls (default 3, env GBNF_GATE_JOBS)")
    ap.add_argument("--json", action="store_true", help="machine-readable summary")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("--dump", type=Path, metavar="DIR", help="write each divergent fragment to DIR/<id>.tk")
    a = ap.parse_args(argv)
    if a.write_fragments:
        return write_fragments()
    g = Grammar.from_file(a.gbnf)
    frags = load_fragments()
    if a.show:
        for f in frags:
            if f["id"] == a.show:
                print(f"--- {f['id']} {f['src']}\n{f['text']}---")
                print("gbnf:", "accept" if g.accepts(f["text"]) else "reject", " parser:", oracle(f["text"]))
                return 0
        print(f"no fragment {a.show}", file=sys.stderr)
        return 2
    if a.only:
        frags = [f for f in frags if f["src"].startswith(a.only)]
    if a.corpus and not a.stress:
        frags = frags + corpus_sample(a.corpus, a.sample)
    if a.stress:
        frags = build_fragments(a.stress, [(c["src"], c["text"]) for c in
                                           (corpus_sample(a.corpus, a.sample) if a.corpus else [])])
    errs = static_checks(g)
    res = run_gate(frags, g, a.verbose, a.jobs)
    bad = len(res["gbnf_only"]) + len(res["parser_only"]) + len(res["known_stale"])
    if a.dump:
        a.dump.mkdir(parents=True, exist_ok=True)
        text = {f["id"]: f["text"] for f in frags}
        for d in res["gbnf_only"] + res["parser_only"]:
            (a.dump / f"{d['id']}.tk").write_text(text[d["id"]], encoding="utf-8")
    if a.json:
        print(json.dumps({**res, "static_errors": errs}, indent=1))
    else:
        print(f"[gbnf] {a.gbnf.relative_to(ROOT) if a.gbnf.is_relative_to(ROOT) else a.gbnf}: "
              f"{len(g.names)} nonterminals, {len(g.prods)} productions")
        for e in errs:
            print(f"  FAIL {e}")
        print(f"[gate] {res['n']} fragments: {res['both_accept']} both accept, {res['both_reject']} both reject, "
              f"{len(res['known_hit'])} known divergences, "
              f"{len(res['gbnf_only'])} gbnf-only accepts, {len(res['parser_only'])} parser-only accepts, "
              f"{len(res['known_stale'])} stale KNOWN entries")
        for d in res["gbnf_only"][:40]:
            print(f"  GBNF-ONLY   {d['id']} {d['src']} (parser: {d['parser']})")
        for d in res["parser_only"][:40]:
            print(f"  PARSER-ONLY {d['id']} {d['src']}")
        for k in res["known_stale"]:
            print(f"  STALE KNOWN {k}: no longer diverges -- delete it ({KNOWN[k]})")
        print("[gate] PASS" if not (bad or errs) else "[gate] FAIL")
    return 1 if (bad or errs) else 0


if __name__ == "__main__":
    sys.exit(main())
