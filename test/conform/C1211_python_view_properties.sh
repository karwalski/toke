#!/usr/bin/env bash
# C1211_python_view_properties.sh — what `tkc --python-view` guarantees beyond
# the golden files of C1210 (story 96.7, docs/decisions/96.7-python-view.md):
#
#   1. Every program under examples/ and every python_view fixture renders
#      (rc 0), and two runs give byte-identical output (deterministic).
#   2. The output opens with the display-only notice.
#   3. The output does not depend on how the file is named on the command
#      line: a relative and an absolute path render identically.
#   4. When python3 is on PATH, every rendering is syntactically valid Python
#      (ast.parse).  This is a property of the printer, not a promise that the
#      text runs: the view is display only.
#   5. A file that does not parse prints nothing on stdout, exits 1 and emits
#      the parser's structured JSON diagnostic (E2002) — the flag never
#      renders a partial AST.
#   6. Several files in one call render one after another, each with its own
#      header; `--help` lists the flag.
#
# Negative control: TKC built from toke main 031d72fd has no --python-view
# ("tkc: unknown flag: --python-view", rc 3): 8 of the 13 checks are red
# there.  The 5 that stay green (determinism, syntax, path independence,
# empty stdout on error, non-empty set) hold vacuously for empty output; they
# guard the implementation, the other 8 prove the flag exists.
#
# Story: 96.7

set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
TKC="${TKC:-${REPO_ROOT}/toke}"
FIX="${SCRIPT_DIR}/fixtures/python_view"
PASS=0; FAIL=0
expect() {
    if [ "$2" = "$3" ]; then echo "PASS $1"; PASS=$((PASS + 1))
    else echo "FAIL $1"; echo "        expected: $3"; echo "        got:      $2"; FAIL=$((FAIL + 1)); fi
}
WORK="$(mktemp -d)"; trap 'rm -rf "${WORK}"' EXIT

FILES=()
while IFS= read -r f; do FILES+=("$f"); done < <(
    cd "${REPO_ROOT}" && { find examples -name '*.tk'; ls test/conform/fixtures/python_view/*.tk; } | LC_ALL=C sort)

HAVE_PY=0; command -v python3 >/dev/null 2>&1 && HAVE_PY=1
n_ok=0; n_det=0; n_hdr=0; n_py=0
for f in "${FILES[@]}"; do
    "${TKC}" --python-view "${REPO_ROOT}/${f}" > "${WORK}/a.py" 2>/dev/null && n_ok=$((n_ok + 1))
    "${TKC}" --python-view "${REPO_ROOT}/${f}" > "${WORK}/b.py" 2>/dev/null
    cmp -s "${WORK}/a.py" "${WORK}/b.py" && n_det=$((n_det + 1))
    sed -n 2p "${WORK}/a.py" | grep -q '^# Display only: not executable, not round-trippable' && n_hdr=$((n_hdr + 1))
    if [ "${HAVE_PY}" = 1 ]; then
        python3 -I -c 'import ast,sys; ast.parse(open(sys.argv[1]).read())' "${WORK}/a.py" 2>/dev/null \
            && n_py=$((n_py + 1))
    else
        n_py=$((n_py + 1))
    fi
done
N=${#FILES[@]}
expect "1 all ${N} files render"            "${n_ok}"  "${N}"
expect "1 all ${N} renderings deterministic" "${n_det}" "${N}"
expect "2 display-only notice on all ${N}"   "${n_hdr}" "${N}"
[ "${HAVE_PY}" = 1 ] || echo "NOTE 4 python3 not found; the syntax check is skipped"
expect "4 all ${N} are valid Python syntax" "${n_py}"  "${N}"
[ "${N}" -ge 16 ] && expect "1 the set is not empty" "ok" "ok" || expect "1 the set is not empty" "${N}" ">=16"

# 3 — path independence
( cd "${FIX}" && "${TKC}" --python-view errors.tk > "${WORK}/rel.py" 2>/dev/null )
"${TKC}" --python-view "${FIX}/errors.tk" > "${WORK}/abs.py" 2>/dev/null
cmp -s "${WORK}/rel.py" "${WORK}/abs.py" && r=same || r=differ
expect "3 relative and absolute path render the same" "${r}" "same"
expect "3 header names the basename" "$(head -1 "${WORK}/abs.py")" \
    '# Python view of errors.tk, generated by `tkc --python-view`.'

# 5 — a parse error renders nothing
printf 'm=bad;\nf=main():i64{\n  let x=;\n  <0\n};\n' > "${WORK}/bad.tk"
"${TKC}" --python-view "${WORK}/bad.tk" > "${WORK}/bad.out" 2> "${WORK}/bad.err"; rc=$?
expect "5 parse error exits 1" "${rc}" "1"
expect "5 parse error prints nothing on stdout" "$(wc -c < "${WORK}/bad.out" | tr -d ' ')" "0"
code="$(grep -o '"error_code":"[^"]*"' "${WORK}/bad.err" | head -1 | cut -d'"' -f4)"
expect "5 parse error is a structured E2002" "${code}" "E2002"

# 6 — several files, and --help
"${TKC}" --python-view "${FIX}/errors.tk" "${FIX}/edges.tk" > "${WORK}/two.py" 2>/dev/null; rc=$?
expect "6 two files exit 0" "${rc}" "0"
expect "6 two files give two headers" "$(grep -c '^# Python view of ' "${WORK}/two.py")" "2"
"${TKC}" --help 2>&1 | grep -q -- '--python-view' && h=listed || h=missing
expect "6 --help lists --python-view" "${h}" "listed"

echo "C1211: ${PASS} passed, ${FAIL} failed"
[ "${FAIL}" -eq 0 ]
